const hash = () => {
  const s4 = () => {
    return Math.floor((1 + Math.random()) * 0x10000)
      .toString(16)
      .substring(1);
  };
  return `${s4()}${s4()}-${s4()}-${s4()}-${s4()}-${s4()}${s4()}${s4()}`;
};
const projectItems = (image, projectUrl, name, category, subCategory) => {
  return {
    id: hash(),
    image: image,
    projectUrl: projectUrl,
    name: name,
    category: category,
    imageArray: subCategory,
  };
};

